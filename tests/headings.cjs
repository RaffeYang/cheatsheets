const fs = require('node:fs'),vm=require('node:vm'),ts=require('typescript'),assert=require('node:assert/strict');
const result={};
const file='src/utils/DocumentHeadings.ts';
assert.ok(fs.existsSync(file),'structural heading parser exists');
vm.runInNewContext(ts.transpile(fs.readFileSync(file,'utf8'),{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2023}),{exports:result});
const {extractHeadings,extractSectionContent}=result;
let text='### 用法\n第一段\n### 用法\n第二段';
let h=extractHeadings(text);
assert.notEqual(h[0].id,h[1].id);
assert.ok(extractSectionContent(text,h[1],true).includes('第二段'));
assert.ok(!extractSectionContent(text,h[1],true).includes('第一段'));
text='# Root\nIntro\n## Parent\n### Child\n```md\n## fake\n```\nKeep\n#### Nested\nNested body\n~~~md\n### fake too\n~~~\n### End\nTail';
h=extractHeadings(text);
assert.deepEqual(Array.from(h,x=>x.text),['Root','Parent','Child','End']);
assert.equal(extractSectionContent(text,h[0],true),'# Root\nIntro');
assert.ok(extractSectionContent(text,h[2],true).includes('Nested body'));
assert.ok(extractSectionContent(text,h[2],true).includes('Keep'));
assert.ok(!extractSectionContent(text,h[2],true).includes('Tail'));
assert.equal(extractSectionContent(text,h[0]),text);
text='<!--\n# Hidden\n-->\n    # Indented code\n### **Rust** `HashMap`\\<K,V\\> ###\r\nBody\r\n';
h=extractHeadings(text);
assert.equal(h.length,1);
assert.equal(h[0].text,'Rust HashMap<K,V>');
assert.ok(extractSectionContent(text,h[0],true).startsWith('### **Rust**'));
assert.equal(extractHeadings('Intro\n'+text)[0].id,h[0].id,'ids stable after unrelated text insertions');
console.log('PASS: duplicate headings, original offsets, fences/comments, nested body and stable clean labels');
